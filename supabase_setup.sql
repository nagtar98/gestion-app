-- 1. Eliminar la tabla previa si existiese
DROP TABLE IF EXISTS usuarios CASCADE;

-- 2. Crear la tabla 'usuarios' con soporte para fotos de perfil (avatar_url)
CREATE TABLE usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  rol TEXT NOT NULL CHECK (rol IN ('Administrador', 'Usuario Estandar')),
  departamento TEXT NOT NULL,
  estado TEXT NOT NULL CHECK (estado IN ('Activo', 'Inactivo')),
  avatar_url TEXT,
  fecha_alta DATE DEFAULT CURRENT_DATE
);

-- 3. Configurar políticas de seguridad de fila (Row Level Security - RLS)
-- Permite que la aplicación web pueda consultar y modificar datos con la Anon Key pública
ALTER TABLE usuarios ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Permitir lectura publica a usuarios" 
  ON usuarios FOR SELECT 
  TO anon, authenticated 
  USING (true);

CREATE POLICY "Permitir insercion a usuarios" 
  ON usuarios FOR INSERT 
  TO anon, authenticated 
  WITH CHECK (true);

CREATE POLICY "Permitir actualizacion a usuarios" 
  ON usuarios FOR UPDATE 
  TO anon, authenticated 
  USING (true);

